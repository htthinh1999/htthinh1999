#!/usr/bin/env node
// Generates the profile metric cards.
//
//   node scripts/profile-metrics/cli.mjs --out dist                 # live data
//   node scripts/profile-metrics/cli.mjs --fixture <raw.json>        # offline preview
//
// Tokens (first one that authenticates wins):
//   METRICS_TOKEN  personal access token — includes private-repo aggregates
//   GITHUB_TOKEN   workflow token — public data only (automatic fallback)

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

import { collect } from './lib/collect.mjs';
import { resolveClient } from './lib/github.mjs';
import { buildModel } from './lib/model.mjs';
import { CARDS } from './lib/render.mjs';
import { THEMES } from './lib/theme.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const log = (message) => console.log(message);

const { values: args } = parseArgs({
  options: {
    out: { type: 'string', default: 'dist' },
    config: { type: 'string', default: path.join(here, 'config.json') },
    fixture: { type: 'string' },
  },
});

async function main() {
  const config = JSON.parse(await readFile(args.config, 'utf8'));
  const started = Date.now();

  let model;
  if (args.fixture) {
    log(`Rendering from fixture ${args.fixture}`);
    const raw = JSON.parse(await readFile(args.fixture, 'utf8'));
    model = buildModel(raw, config, raw.now ? new Date(raw.now) : new Date());
  } else {
    const { client, tokenName } = await resolveClient(
      [
        { name: 'METRICS_TOKEN', token: process.env.METRICS_TOKEN },
        { name: 'GITHUB_TOKEN', token: process.env.GITHUB_TOKEN },
      ],
      { log },
    );
    if (tokenName !== 'METRICS_TOKEN') {
      log('! Personal token unavailable — cards will only reflect public data.');
    }
    const raw = await collect(client, config, { log });
    model = buildModel(raw, config);
  }

  await mkdir(args.out, { recursive: true });
  const written = [];
  for (const [card, render] of Object.entries(CARDS)) {
    for (const theme of Object.values(THEMES)) {
      const file = `${card}-${theme.name}.svg`;
      await writeFile(path.join(args.out, file), render(model, theme));
      written.push(file);
    }
  }
  // Aggregates only — no repository names — safe to publish.
  await writeFile(path.join(args.out, 'metrics.json'), `${JSON.stringify(model, null, 2)}\n`);
  await writeFile(
    path.join(args.out, 'README.md'),
    [
      '# Profile metrics',
      '',
      `Generated by [\`profile-metrics.yml\`](https://github.com/${config.login}/${config.login}/blob/main/.github/workflows/profile-metrics.yml).`,
      'This branch is force-pushed on every run — do not commit to it.',
      '',
      `Last generated: ${model.generatedAt}`,
      '',
    ].join('\n'),
  );

  log(`Wrote ${written.length} cards to ${args.out}/ in ${((Date.now() - started) / 1000).toFixed(1)}s`);
  log(
    `  ${model.contributions.thisYear} contributions in ${model.year} · ` +
      `streak ${model.streaks.current.length}d (best ${model.streaks.longest.length}d) · ` +
      `${model.rhythm.total} commits analysed · ${model.languages.items.length} languages`,
  );
}

main().catch((error) => {
  console.error(`✖ ${error.message}`);
  process.exitCode = 1;
});
